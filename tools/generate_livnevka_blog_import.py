def blog_import() -> dict[str, object]:
    posts = []
    for index, post in enumerate(POSTS):
        acf = dict(post["acf"])
        acf["blogseo_related_service_slugs"] = post["related"]
        acf["blogseo_seo_title"] = post["seo_title"]
        acf["blogseo_seo_description"] = post["seo_description"]
        posts.append(
            {
                "slug": post["slug"],
                "post_title": post["post_title"],
                "post_excerpt": post["excerpt"],
                "post_content": post["excerpt"],
                "menu_order": index,
                "categories": [91, 72],
                "featured_image_url": acf["blogseo_main_image_url"],
                "acf": acf,
            }
        )
    return {"type": "livnevka_blog_posts", "category_ids": [91, 72], "posts": posts}


def write_json(path: Path, payload: object) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(payload, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")


def main() -> None:
    payload = blog_import()
    write_json(SEO_BLOG_IMPORT_PATH, payload)
    write_json(THEME_BLOG_IMPORT_PATH, payload)
    print(f"Wrote {SEO_BLOG_IMPORT_PATH}")
    print(f"Wrote {THEME_BLOG_IMPORT_PATH}")


if __name__ == "__main__":
    main()
