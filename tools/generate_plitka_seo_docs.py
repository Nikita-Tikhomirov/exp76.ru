def parse_price_row(row: str) -> dict:
    service = row.strip()
    price = ""
    term = ""
    if " — " in row:
        service, rest = row.split(" — ", 1)
        if ", сроки " in rest:
            price, term = rest.split(", сроки ", 1)
        else:
            price = rest
    return {"service": service.strip(), "price": price.strip(), "term": term.strip()}


def render_content(page: dict) -> str:
    parts = []
    for heading, paragraphs in page.get("content_sections", []):
        parts.append(f"<h2>{heading}</h2>")
        parts.extend(f"<p>{paragraph}</p>" for paragraph in paragraphs)
    if page.get("problem_items"):
        parts.append(f"<h2>{page['problem_title']}</h2>")
        parts.append(f"<p>{page['problem_text']}</p>")
        parts.append("<ul>" + "".join(f"<li>{item}</li>" for item in page["problem_items"]) + "</ul>")
        parts.append(f"<h2>{page['solution_title']}</h2>")
        parts.append(f"<p>{page['solution_text']}</p>")
        parts.append("<ul>" + "".join(f"<li>{item}</li>" for item in page["solution_points"]) + "</ul>")
        parts.append(f"<h2>{page['faq_title']}</h2>")
        for question, answer in page["faq"]:
            parts.append(f"<h3>{question}</h3><p>{answer}</p>")
    return "\n".join(parts)


