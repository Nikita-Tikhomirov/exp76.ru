def main() -> None:
    import_dir = ROOT / "import"
    import_dir.mkdir(parents=True, exist_ok=True)
    payload = {
        "category": build_category_payload(),
        "posts": [build_post_payload(page) for page in SERVICES],
        "cleanup": {
            "category_id": CATEGORY_ID,
            "keep_slugs": [page["slug"] for page in SERVICES],
            "delete_stale_posts": True,
        },
    }
    with (import_dir / "autopoliv-import.json").open("w", encoding="utf-8") as fp:
        json.dump(payload, fp, ensure_ascii=False, indent=2)


if __name__ == "__main__":
    main()
