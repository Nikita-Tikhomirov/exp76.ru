def create_doc() -> Document:
    doc = Document()
    style = doc.styles["Normal"]
    style.font.name = "Calibri"
    style.font.size = Pt(11)
    return doc


def add_kv(doc: Document, key: str, value: str) -> None:
    paragraph = doc.add_paragraph()
    paragraph.add_run(f"{key}: ").bold = True
    paragraph.add_run(value)


def add_bullets(doc: Document, items: list[str]) -> None:
    for item in items:
        doc.add_paragraph(item, style="List Bullet")


def add_rows(doc: Document, rows: list[str]) -> None:
    for row in rows:
        doc.add_paragraph(row)


def add_faq(doc: Document, faq_items: list[tuple[str, str]]) -> None:
    for question, answer in faq_items:
        doc.add_paragraph(question, style="List Bullet")
        doc.add_paragraph(answer)


def parse_price_row(row: str) -> dict:
    service = row.strip()
    price = ""
    term = ""

    delimiter = " — " if " — " in row else " - "
    if delimiter in row:
        service, rest = row.split(delimiter, 1)
        service = service.strip()
        rest = rest.strip()

        term_delimiter = ", сроки "
        if term_delimiter in rest:
            price, term = rest.split(term_delimiter, 1)
            price = price.strip()
            term = term.strip()
        else:
            price = rest

    return {
        "service": service,
        "price": price,
        "term": term,
    }


def render_main_content_html(page: dict) -> str:
    sections_html = []
    for heading, paragraphs in page["content_sections"]:
        paragraph_html = "".join(f"<p>{paragraph}</p>" for paragraph in paragraphs)
        sections_html.append(f"<h2>{heading}</h2>{paragraph_html}")
    return "\n".join(sections_html)


def render_service_post_content_html(page: dict) -> str:
    if "problem_items" not in page:
        return render_main_content_html(page)

    problem_items_html = "".join(f"<li>{item}</li>" for item in page["problem_items"])
    solution_points_html = "".join(f"<li>{item}</li>" for item in page["solution_points"])

    faq_html_parts = []
    for question, answer in page["faq"]:
        faq_html_parts.append(f"<h3>{question}</h3><p>{answer}</p>")

    return "\n".join(
        [
            f"<h2>{page['problem_title']}</h2>",
            f"<p>{page['problem_text']}</p>",
            f"<ul>{problem_items_html}</ul>",
            f"<h2>{page['solution_title']}</h2>",
            f"<p>{page['solution_text']}</p>",
            f"<ul>{solution_points_html}</ul>",
            f"<h2>{page['faq_title']}</h2>",
            "".join(faq_html_parts),
        ]
    )


def get_section_heading(page: dict, index: int, fallback: str) -> str:
    sections = page.get("content_sections", [])
    if len(sections) > index:
        return sections[index][0]
    return fallback


def get_section_text(page: dict, index: int, fallback: str) -> str:
    sections = page.get("content_sections", [])
    if len(sections) > index and sections[index][1]:
        return sections[index][1][0]
    return fallback


