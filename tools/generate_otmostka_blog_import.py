def blog_import() -> dict[str, object]:
    posts = []
    for index, item in enumerate(POSTS):
        acf = dict(item["acf"])
        acf["blogseo_related_service_slugs"] = item["related"]
        acf["blogseo_seo_title"] = item["seo_title"]
        acf["blogseo_seo_description"] = item["seo_description"]
        posts.append(
            {
                "slug": item["slug"],
                "post_title": item["post_title"],
                "post_excerpt": item["excerpt"],
                "post_content": item["excerpt"],
                "menu_order": index,
                "categories": [88, 72],
                "featured_image_url": acf["blogseo_main_image_url"],
                "acf": acf,
            }
        )
    return {"type": "otmostka_blog_posts", "category_ids": [88, 72], "posts": posts}


def write_json(path: Path, payload: object) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(payload, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")


